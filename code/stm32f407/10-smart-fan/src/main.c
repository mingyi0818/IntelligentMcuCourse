/* Display integer */
static void OLED_ShowNumber(uint8_t page, uint8_t col, uint32_t num)
{
    char buf[12];
    int len = sprintf(buf, "%lu", num);
    int i, j;
    for (i = 0; i < len; i++)
    {
        uint8_t digit = buf[i] - '0';
        OLED_SetCursor(page, col + i * 8);
        for (j = 0; j < 8; j++) OLED_WriteDat(font_8x16[digit][j]);
        OLED_SetCursor(page + 1, col + i * 8);
        for (j = 8; j < 16; j++) OLED_WriteDat(font_8x16[digit][j]);
    }
}

/* ===== PID controller struct ===== */
typedef struct {
    float setpoint;   /* Setpoint */
    float Kp, Ki, Kd; /* PID coefficients */
    float integral;   /* Integral accumulator */
    float lastError;  /* Last error */
} PID_Controller;

/* PID compute: returns control output (0~1000 range for PWM) */
static float PID_Compute(PID_Controller *pid, float current)
{
    float error = pid->setpoint - current;  /* Error: setpoint - current */
    pid->integral += error;
    /* Integral clamping to prevent integral windup */
    if (pid->integral > 200.0f) pid->integral = 200.0f;
    if (pid->integral < -200.0f) pid->integral = -200.0f;
    float derivative = error - pid->lastError;
    pid->lastError = error;
    /* PID output = Kp*e + Ki*integral(e) + Kd*de/dt */
    float output = pid->Kp * error + pid->Ki * pid->integral + pid->Kd * derivative;
    /* Clamp output to PWM range 0~1000 */
    if (output < 0) output = 0;
    if (output > FAN_PWM_MAX) output = FAN_PWM_MAX;
    return output;
}

/* ===== Main function ===== */
int main(void)
{
    HAL_Init();
    SystemClock_Config();
    MX_GPIO_Init();
    MX_TIM3_Init();
    MX_I2C1_Init();
    MX_USART1_UART_Init();

    /* Start fan PWM */
    HAL_TIM_PWM_Start(&htim3, FAN_PWM_CH);

    /* Initialize OLED */
    OLED_Init();
    OLED_Clear();

    /* PID initialization */
    PID_Controller pid = {
        .setpoint = 30.0f,  /* Initial threshold 30 C */
        .Kp = PID_KP,
        .Ki = PID_KI,
        .Kd = PID_KD,
        .integral = 0,
        .lastError = 0
    };

    /* Threshold levels array */
    const float thresholds[] = {28.0f, 30.0f, 32.0f, 34.0f};
    const uint8_t numThresholds = sizeof(thresholds) / sizeof(thresholds[0]);
    uint8_t thresholdIdx = 1; /* Default 30 C */
    pid.setpoint = thresholds[thresholdIdx];

    uint8_t lastBtnState = 1;
    uint32_t lastBtnTime = 0;

    printf("\r\n===== Smart Fan System =====\r\n");
    printf("PID: Kp=%.1f Ki=%.1f Kd=%.1f\r\n", pid.Kp, pid.Ki, pid.Kd);

    /* ===== Main loop ===== */
    while (1)
    {
        /* 1. Read temperature */
        float temp = DS18B20_ReadTemp();

        /* 2. Button detection (threshold switching) */
        uint8_t btnState = HAL_GPIO_ReadPin(BUTTON_PORT, BUTTON_PIN);
        if (lastBtnState == 1 && btnState == 0)
        {
            /* Debounce: read again after 50ms */
            if (HAL_GetTick() - lastBtnTime > 50)
            {
                thresholdIdx = (thresholdIdx + 1) % numThresholds;
                pid.setpoint = thresholds[thresholdIdx];
                printf("Threshold changed to %.1f C\r\n", pid.setpoint);
                lastBtnTime = HAL_GetTick();
            }
        }
        lastBtnState = btnState;

        /* 3. PID compute and output PWM */
        float pwmValue = 0;
        if (temp >= -100.0f) /* Temperature valid */
        {
            pwmValue = PID_Compute(&pid, temp);
            __HAL_TIM_SET_COMPARE(&htim3, FAN_PWM_CH, (uint16_t)pwmValue);

            /* Fan running indicator: LED on when temp > threshold */
            if (temp > pid.setpoint)
            {
                HAL_GPIO_WritePin(LED_PORT, LED_PIN, GPIO_PIN_SET);
            }
            else
            {
                HAL_GPIO_WritePin(LED_PORT, LED_PIN, GPIO_PIN_RESET);
            }
        }

        /* 4. UART debug output */
        printf("Temp: %.2fC, Threshold: %.1fC, PWM: %.0f\r\n",
               temp, pid.setpoint, pwmValue);

        /* 5. OLED display temperature and threshold */
        OLED_SetCursor(0, 0);
        if (temp >= 0 && temp < 100)
        {
            /* Display integer part of temperature */
            OLED_ShowNumber(0, 0, (uint32_t)(temp + 0.5f));
        }
        OLED_SetCursor(2, 0);
        OLED_ShowNumber(2, 0, (uint32_t)pid.setpoint);

        /* 6. Sampling period 1 second */
        HAL_Delay(1000);
    }
}

