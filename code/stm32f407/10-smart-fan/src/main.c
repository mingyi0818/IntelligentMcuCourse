/* ===== DS18B20 one-wire driver ===== */

/* Microsecond-level delay (approximate, loop delay at 168MHz) */
static void DS18B20_DelayUs(uint32_t us)
{
    /* At 168MHz each loop iteration is about 1/168us, multiplied by a factor for approximation */
    uint32_t i;
    for (i = 0; i < us * 14; i++)
    {
        __NOP();
    }
}

/* Set data line direction: 1=output, 0=input */
static void DS18B20_SetMode(uint8_t isOutput)
{
    GPIO_InitTypeDef GPIO_InitStruct = {0};
    GPIO_InitStruct.Pin = DS18B20_PIN;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    if (isOutput)
    {
        GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
        GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    }
    else
    {
        GPIO_InitStruct.Mode = GPIO_MODE_INPUT;
        GPIO_InitStruct.Pull = GPIO_PULLUP;
    }
    HAL_GPIO_DeInit(DS18B20_PORT, DS18B20_PIN);
    HAL_GPIO_Init(DS18B20_PORT, &GPIO_InitStruct);
    g_dqMode = isOutput;
}

/* Write one byte */
static void DS18B20_WriteByte(uint8_t data)
{
    uint8_t i;
    DS18B20_SetMode(1);
    for (i = 0; i < 8; i++)
    {
        /* Pull low to start write time slot */
        HAL_GPIO_WritePin(DS18B20_PORT, DS18B20_PIN, GPIO_PIN_RESET);
        DS18B20_DelayUs(2);
        /* Write 1: release bus; Write 0: keep low */
        if (data & 0x01)
        {
            HAL_GPIO_WritePin(DS18B20_PORT, DS18B20_PIN, GPIO_PIN_SET);
        }
        DS18B20_DelayUs(60);
        HAL_GPIO_WritePin(DS18B20_PORT, DS18B20_PIN, GPIO_PIN_SET);
        DS18B20_DelayUs(2);
        data >>= 1;
    }
}

/* Read one byte */
static uint8_t DS18B20_ReadByte(void)
{
    uint8_t data = 0;
    uint8_t i;
    for (i = 0; i < 8; i++)
    {
        DS18B20_SetMode(1);
        HAL_GPIO_WritePin(DS18B20_PORT, DS18B20_PIN, GPIO_PIN_RESET);
        DS18B20_DelayUs(2);
        HAL_GPIO_WritePin(DS18B20_PORT, DS18B20_PIN, GPIO_PIN_SET);
        DS18B20_SetMode(0);
        DS18B20_DelayUs(10);
        if (HAL_GPIO_ReadPin(DS18B20_PORT, DS18B20_PIN))
        {
            data |= (1 << i);
        }
        DS18B20_DelayUs(50);
    }
    return data;
}

/* Reset and detect presence pulse: returns 0 if detected, 1 if no response */
static uint8_t DS18B20_Reset(void)
{
    uint8_t presence;
    DS18B20_SetMode(1);
    HAL_GPIO_WritePin(DS18B20_PORT, DS18B20_PIN, GPIO_PIN_RESET);
    DS18B20_DelayUs(480);
    HAL_GPIO_WritePin(DS18B20_PORT, DS18B20_PIN, GPIO_PIN_SET);
    DS18B20_SetMode(0);
    DS18B20_DelayUs(70);
    /* Low level read indicates presence */
    presence = HAL_GPIO_ReadPin(DS18B20_PORT, DS18B20_PIN);
    DS18B20_DelayUs(410);
    return presence; /* 0=present, 1=none */
}

/* Read temperature (Celsius), returns -999 on failure */
float DS18B20_ReadTemp(void)
{
    uint8_t tempL, tempH;
    int16_t raw;

    if (DS18B20_Reset() != 0)
    {
        return -999.0f; /* No response */
    }
    DS18B20_WriteByte(0xCC); /* Skip ROM */
    DS18B20_WriteByte(0x44); /* Start temperature conversion */
    HAL_Delay(750);          /* 12-bit conversion requires 750ms */

    if (DS18B20_Reset() != 0)
    {
        return -999.0f;
    }
    DS18B20_WriteByte(0xCC); /* Skip ROM */
    DS18B20_WriteByte(0xBE); /* Read scratchpad */
    tempL = DS18B20_ReadByte();
    tempH = DS18B20_ReadByte();
    raw = (int16_t)((tempH << 8) | tempL);
    /* 12-bit resolution: 0.0625 C/LSB */
    return (float)raw * 0.0625f;
}

/* ===== OLED basic functions (same as project 07, simplified) ===== */
static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {OLED_CMD, cmd};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, buf, 2, HAL_MAX_DELAY);
}

static void OLED_WriteDat(uint8_t dat)
{
    uint8_t buf[2] = {OLED_DAT, dat};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDR, buf, 2, HAL_MAX_DELAY);
}

static void OLED_Init(void)
{
    HAL_Delay(100);
    OLED_WriteCmd(0xAE);
    OLED_WriteCmd(0xD5); OLED_WriteCmd(0x80);
    OLED_WriteCmd(0xA8); OLED_WriteCmd(0x3F);
    OLED_WriteCmd(0xD3); OLED_WriteCmd(0x00);
    OLED_WriteCmd(0x40);
    OLED_WriteCmd(0x8D); OLED_WriteCmd(0x14);
    OLED_WriteCmd(0x20); OLED_WriteCmd(0x02);
    OLED_WriteCmd(0xA1);
    OLED_WriteCmd(0xC8);
    OLED_WriteCmd(0xDA); OLED_WriteCmd(0x12);
    OLED_WriteCmd(0x81); OLED_WriteCmd(0xCF);
    OLED_WriteCmd(0xD9); OLED_WriteCmd(0xF1);
    OLED_WriteCmd(0xDB); OLED_WriteCmd(0x40);
    OLED_WriteCmd(0xA4);
    OLED_WriteCmd(0xA6);
    OLED_WriteCmd(0xAF);
}

static void OLED_Clear(void)
{
    uint8_t page, col;
    for (page = 0; page < 8; page++)
    {
        OLED_WriteCmd(0xB0 + page);
        OLED_WriteCmd(0x00);
        OLED_WriteCmd(0x10);
        for (col = 0; col < 128; col++)
        {
            OLED_WriteDat(0x00);
        }
    }
}

static void OLED_SetCursor(uint8_t page, uint8_t col)
{
    OLED_WriteCmd(0xB0 + page);
    OLED_WriteCmd(col & 0x0F);
    OLED_WriteCmd(0x10 | (col >> 4));
}

